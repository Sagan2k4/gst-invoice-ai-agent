package com.gstagent.report;

import com.gstagent.report.GstSummary.*;
import com.lowagie.text.*;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import org.springframework.stereotype.Component;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;
import java.text.NumberFormat;
import java.time.format.DateTimeFormatter;
import java.util.Locale;

/** Printable monthly GST summary for the business owner / CA. */
@Component
public class PdfReportGenerator {

    private static final Font TITLE = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 16);
    private static final Font H2 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 11);
    private static final Font BODY = FontFactory.getFont(FontFactory.HELVETICA, 8);
    private static final Font BODY_BOLD = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 8);
    private static final Font MUTED = FontFactory.getFont(FontFactory.HELVETICA, 9, Color.GRAY);
    private static final Color HEADER_BG = new Color(235, 238, 242);
    private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("dd-MM-yyyy");

    public byte[] generate(GstSummary s) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document doc = new Document(PageSize.A4.rotate(), 28, 28, 28, 28);
        PdfWriter.getInstance(doc, out);
        doc.open();

        doc.add(new Paragraph("GST Purchase Summary — " + s.period().format(DateTimeFormatter.ofPattern("MMMM yyyy")), TITLE));
        doc.add(new Paragraph(s.businessName() + (s.businessGstin() == null ? "" : "   GSTIN: " + s.businessGstin()), MUTED));
        doc.add(new Paragraph((s.approvedOnly() ? "Approved bills only" : "Validated and approved bills")
                + "  •  " + s.invoiceCount() + " bills included  •  " + s.pendingReviewCount() + " pending review", MUTED));
        doc.add(Chunk.NEWLINE);

        Totals t = s.totals();
        PdfPTable totals = table(new float[]{1, 1, 1, 1, 1, 1, 1, 1},
                "Taxable value", "CGST", "SGST", "IGST", "Cess", "Total tax", "Eligible ITC", "Blocked ITC");
        row(totals, t.taxableValue(), t.cgst(), t.sgst(), t.igst(), t.cess(), t.totalTax(), s.eligibleItc(), s.blockedItc());
        doc.add(totals);

        section(doc, "Category-wise");
        PdfPTable cat = table(new float[]{3, 1, 1, 2, 2}, "Category", "ITC", "Bills", "Taxable", "Tax");
        for (CategoryRow c : s.byCategory()) {
            row(cat, c.label(), c.itcEligible() ? "Eligible" : "Blocked", c.invoiceCount(), c.taxableValue(), c.totalTax());
        }
        doc.add(cat);

        section(doc, "Rate-wise");
        PdfPTable rate = table(new float[]{1, 2, 2, 2, 2}, "Rate %", "Taxable", "CGST", "SGST", "IGST");
        for (RateRow r : s.byRate()) {
            row(rate, r.gstRate().toPlainString() + "%", r.taxableValue(), r.cgst(), r.sgst(), r.igst());
        }
        doc.add(rate);

        section(doc, "HSN/SAC-wise");
        PdfPTable hsn = table(new float[]{1.2f, 4, 1, 1, 1.5f, 1.3f, 1.3f, 1.3f},
                "HSN/SAC", "Description", "Qty", "Rate %", "Taxable", "CGST", "SGST", "IGST");
        for (HsnRow h : s.byHsn()) {
            row(hsn, h.hsnSac(), h.description(), h.quantity().stripTrailingZeros().toPlainString(),
                    h.gstRate().toPlainString(), h.taxableValue(), h.cgst(), h.sgst(), h.igst());
        }
        doc.add(hsn);

        section(doc, "Invoice register");
        PdfPTable inv = table(new float[]{1.2f, 1.4f, 3, 2, 0.8f, 1.5f, 1.2f, 1.2f, 1.2f, 1.5f},
                "Date", "Invoice No", "Supplier", "GSTIN", "Supply", "Taxable", "CGST", "SGST", "IGST", "Total");
        for (InvoiceRow i : s.invoices()) {
            row(inv, i.invoiceDate() == null ? "" : i.invoiceDate().format(DATE), i.invoiceNumber(), i.supplierName(),
                    i.supplierGstin(), i.supplyType(), i.taxableValue(), i.cgst(), i.sgst(), i.igst(), i.totalAmount());
        }
        row(inv, "", "", "Total", "", "", t.taxableValue(), t.cgst(), t.sgst(), t.igst(), t.totalAmount());
        doc.add(inv);

        doc.add(Chunk.NEWLINE);
        doc.add(new Paragraph("Generated by GST Invoice Agent. Reconcile with GSTR-2B before claiming input tax credit.", MUTED));
        doc.close();
        return out.toByteArray();
    }

    private void section(Document doc, String title) {
        Paragraph p = new Paragraph(title, H2);
        p.setSpacingBefore(12);
        p.setSpacingAfter(4);
        doc.add(p);
    }

    private PdfPTable table(float[] widths, String... headers) {
        PdfPTable table = new PdfPTable(widths);
        table.setWidthPercentage(100);
        table.setHeaderRows(1);
        for (String h : headers) {
            PdfPCell cell = new PdfPCell(new Phrase(h, BODY_BOLD));
            cell.setBackgroundColor(HEADER_BG);
            cell.setPadding(4);
            table.addCell(cell);
        }
        return table;
    }

    private void row(PdfPTable table, Object... values) {
        for (Object v : values) {
            PdfPCell cell;
            if (v instanceof BigDecimal b) {
                cell = new PdfPCell(new Phrase(inr(b), BODY));
                cell.setHorizontalAlignment(Element.ALIGN_RIGHT);
            } else {
                cell = new PdfPCell(new Phrase(v == null ? "" : v.toString(), BODY));
            }
            cell.setPadding(3);
            table.addCell(cell);
        }
    }

    /** Indian digit grouping, e.g. 1,25,000.00. */
    static String inr(BigDecimal v) {
        NumberFormat f = NumberFormat.getNumberInstance(Locale.forLanguageTag("en-IN"));
        f.setMinimumFractionDigits(2);
        f.setMaximumFractionDigits(2);
        return f.format(v);
    }
}
